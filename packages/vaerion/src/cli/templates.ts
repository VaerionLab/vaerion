export const TEMPLATE_IDS: readonly string[] = Object.freeze(Object.keys(TEMPLATES));

/** Substitute the NAME_TITLE / PLACEHOLDER_NAME / @NAME tokens. */
export function materialize(projectName: string, templateId: string): TemplateFile[] {
  const template = TEMPLATES[templateId];
  if (template === undefined) {
    throw new Error(`unknown template: ${templateId}`);
  }
  return template.files(projectName).map((f) => ({
    path: f.path,
    contents: f.contents.replaceAll("NAME_TITLE", projectName).replaceAll("PLACEHOLDER_NAME", projectName).replaceAll("@NAME", `@${projectName}`),
  }));
}
