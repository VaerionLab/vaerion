const DEBT_MARKERS = ["TO" + "DO", "FIX" + "ME", "XX" + "X", "HA" + "CK"];
export const DEBT_PATTERN = new RegExp("\\b(" + DEBT_MARKERS.join("|") + ")\\b");

function tsconfig(): string {
  return `{
  "compilerOptions": {
    "target": "esnext",
    "module": "esnext",
    "moduleResolution": "bundler",
    "types": ["bun-types"],
    "strict": true,
    "noUncheckedIndexedAccess": true,
    "noEmit": true,
    "skipLibCheck": true
  },
  "include": ["src/**/*.ts", "test/**/*.ts"]
}
`;
}

function packageJson(name: string, opts: { bin?: string; scripts?: Record<string, string> }): string {
  const pkg = {
    name,
    version: "0.1.0",
    private: true,
    type: "module",
    ...(opts.bin !== undefined ? { bin: { [name]: opts.bin } } : {}),
    scripts: { test: "bun test", ...(opts.scripts ?? {}) },
    devDependencies: { "@types/bun": "^1.3.0" },
  };
  return JSON.stringify(pkg, null, 2) + "\n";
}

/** The workspace config every template emits — strict-schema 0.1, validated
 *  by the engine loader before materialization. */
function vaerionYaml(name: string, opts: { description: string; researchDocs?: boolean; gatewayMockbrain?: boolean; agents?: boolean }): string {
  const parts: string[] = [
    `# Vaerion project configuration (schema 0.1) — generated by Vaerion ${"0.1.7-rc2"}`,
    `# Unknown keys are rejected by law — see spec/schemas/vaerion-yaml.schema.json`,
    `schemaVersion: "0.1"`,
    `project:`,
    `  name: ${name}`,
    `  description: "${opts.description}"`,
  ];
  if (opts.researchDocs === true) {
    parts.push(
      `research:`,
      `  capabilities:`,
      `    - name: project-docs`,
      `      sources:`,
      `        - { kind: local, path: "./docs" }`,
      `      fencing: untrusted`,
      `      maxItems: 100`,
    );
  }
  if (opts.gatewayMockbrain === true || opts.agents === true) {
    parts.push(
      `gateway:`,
      `  providers:`,
      `    mockbrain:`,
      `      enabled: true`,
      `      models:`,
      `        - mock-1`,
      `  budgets:`,
      `    tokensPerRun: 100000`,
    );
  }
  if (opts.agents === true) {
    parts.push(
      `agents:`,
      `  maxSteps: 24`,
      `  plannerModel: mockbrain/mock-1`,
    );
  }
  parts.push(`telemetry:`, `  enabled: false`);
  return parts.join("\n") + "\n";
}

