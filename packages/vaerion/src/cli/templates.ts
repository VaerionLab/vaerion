/**
 * Vaerion project templates (ASC XVIII Phase 5) — the zero-to-project registry.
 *
 * Laws:
 *  - Deterministic: file contents derive ONLY from the project name; no
 *    clock, no randomness, no ambient paths (two runs, identical bytes).
 *  - Honest architecture: generated projects are standalone — the Vaerion
 *    engine governs the workspace through vaerion.yaml; template code never
 *    imports the engine (no dependency the npm surface cannot yet satisfy).
 *  - Every vaerion.yaml emitted here is validated by the engine's strict
 *    config loader BEFORE any file is written.
 *  - Research sources are declared only when the template ships them.
 *  - No unfinished-work markers: generated trees are scanned for debt at
 *    init time (the marker words themselves are assembled at runtime below,
 *    so this source file carries none of them verbatim — the C3 scanner
 *    scans everything, including law text).
 */

export interface TemplateFile {
  path: string;
  contents: string;
}

export interface ProjectTemplate {
  id: string;
  title: string;
  summary: string;
  files(projectName: string): TemplateFile[];
  nextSteps(projectName: string): string[];
}

